"""Render versioned Mermaid sources to SVG; optionally produce PNG review previews.

No source is generated by an image model. Install Mermaid CLI only in .work and
supply an installed Chrome/Chromium executable (headless rendering, no live UI).
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import tempfile
from pathlib import Path


def render(browser: Path, *, previews: Path | None = None, cli: Path | None = None) -> list[str]:
    repo = Path(__file__).resolve().parents[1]
    cli = cli or repo / ".work/diagram-tools/node_modules/@mermaid-js/mermaid-cli/src/cli.js"
    node = shutil.which("node")
    if node is None or not cli.is_file() or not browser.is_file():
        raise ValueError("install Mermaid CLI under .work/diagram-tools and provide a browser path")
    work = repo / ".work"
    work.mkdir(exist_ok=True)
    config_dir = Path(tempfile.mkdtemp(prefix="diagram-render-", dir=work))
    puppet = config_dir / "puppeteer.json"
    puppet.write_text(json.dumps({"executablePath": str(browser.resolve()), "headless": True}))
    source_dir = repo / "docs/diagrams"
    output_dir = repo / "assets/diagrams/reference"
    output_dir.mkdir(parents=True, exist_ok=True)
    if previews is not None:
        previews.mkdir(parents=True, exist_ok=True)
    rendered = []
    for source in sorted(source_dir.glob("*.mmd")):
        targets = [output_dir / (source.stem + ".svg")]
        if previews is not None:
            targets.append(previews / (source.stem + ".png"))
        for target in targets:
            subprocess.run(
                [
                    node,
                    str(cli),
                    "--input",
                    str(source),
                    "--output",
                    str(target),
                    "--configFile",
                    str(source_dir / "theme.json"),
                    "--puppeteerConfigFile",
                    str(puppet),
                    "--svgId",
                    source.stem,
                    "--backgroundColor",
                    "white",
                    "--size",
                    "900" if target.suffix == ".png" else "1000",
                    "--quiet",
                ],
                check=True,
                timeout=90,
            )
        rendered.append(source.stem)
    return rendered


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--browser", required=True, type=Path)
    parser.add_argument("--previews", type=Path)
    parser.add_argument("--cli", type=Path, help="Use an existing Mermaid CLI installation")
    args = parser.parse_args()
    print(json.dumps({"rendered": render(args.browser, previews=args.previews, cli=args.cli)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
